def blank():
    return [[None] * SW for _ in range(SH)]


def put(buf, x, y, c):
    if 0 <= x < SW and 0 <= y < SH:
        buf[y][x] = c


def rows32(text: str) -> list[str]:
    out = []
    for raw in text.strip("\n").splitlines():
        line = raw.split("#", 1)[0].rstrip("\n")
        if len(line) < SW:
            line = line + "." * (SW - len(line))
        out.append(line[:SW])
    while len(out) < SH:
        out.append("." * SW)
    return out[:SH]


def paint_map(buf, grid, pal, ox=0, oy=0):
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch in (".", " ", ""):
                continue
            col = pal.get(ch)
            if col is not None:
                put(buf, ox + x, oy + y, col)


def to_image(buf) -> Image.Image:
    img = new(SW, SH)
    px = img.load()
    for y in range(SH):
        for x in range(SW):
            c = buf[y][x]
            if c is not None:
                px[x, y] = c
    return img


def shadow(buf, cx=16, cy=38):
    for dy in range(-1, 2):
        for dx in range(-7, 8):
            if (dx * dx) / 49 + (dy * dy) / 3 <= 1:
                put(buf, cx + dx, cy + dy, P(18, 14, 20, 140))


def spec_pal(spec):
    h, s, c = spec["hair_pal"], spec["skin_pal"], spec["cloth"]
    mouth = P(196, 110, 118) if not spec.get("male") else s["D"]
    return {
        "K": INK,
        "1": h["1"], "2": h["2"], "3": h["3"], "4": h["4"],
        "S": s["S"], "s": s["s"], "D": s["D"], "B": s["B"],
        "E": EYE, "W": WHITE, "M": mouth,
        "C": c["C"], "c": c["c"], "d": c["d"],
        "L": spec.get("lining", P(22, 22, 28)),
        "A": spec.get("accent", c["C"]),
        "a": spec.get("accent_h", c["c"]),
        "P": PANTS, "p": PANTS_H, "N": SHOE,
        "F": spec.get("acc_c", WHITE),
        "G": P(214, 176, 78),
        "R": P(214, 210, 218),
        "I": INK,
        "U": P(18, 14, 20, 140),
        "H": spec.get("hood_c", c["d"]),
    }


def _cloth(d, C, c):
    return {"d": d, "C": C, "c": c}


