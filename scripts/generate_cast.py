def make_sheet(sprites, labels=None, title=None, scale=4):
    pad = 10
    cell_w, cell_h = SW * scale, SH * scale
    cols = 8
    W = cols * cell_w + (cols + 1) * pad
    H = cell_h + 2 * pad + 18
    sheet = Image.new("RGBA", (W, H), (18, 20, 28, 255))
    d = ImageDraw.Draw(sheet)
    if title:
        d.text((pad, 2), title, fill=(200, 168, 120, 255))
    for i, sp in enumerate(sprites):
        x = pad + i * (cell_w + pad)
        y = pad
        big = zoom(sp, scale)
        sheet.paste(big, (x, y), big)
        name = labels[i] if labels else f"cast_{i+1:02d}"
        d.text((x + 4, y + cell_h + 2), name, fill=(168, 176, 192, 255))
    return sheet


