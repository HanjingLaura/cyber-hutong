def compose_layers(*layers) -> list[str]:
    g = blank_grid()
    for i, layer in enumerate(layers):
        if not layer:
            continue
        if i != 0:
            layer = [r.replace("U", ".") for r in layer]
        g = overlay(g, layer)
    return g


def _layers_for(spec, view, frame=0):
    b = base_pieces(spec.get("male", False))
    hb = hair_only(spec["hair_back"])
    hf = hair_only(spec["hair_front"])
    hs = hair_only(spec["hair_side"])
    hr = hair_only(spec["hair_rear"])
    extras_f = spec.get("extras_front") or ()
    extras_s = spec.get("extras_side") or ()
    extras_b = spec.get("extras_back") or ()

    if view in ("front", "walk"):
        if view == "walk":
            body = b["body_w0"] if frame % 2 == 0 else b["body_w1"]
            head = b["head"]
            if frame % 2:
                head = shift(head, dy=0, dx=0)
                hf = shift(hf, dy=0)
                hb = shift(hb, dy=0)
        elif frame % 4 == 1:
            body = shift(b["body"], dy=-1)
            head = shift(b["head_blink"], dy=-1)
            hf = shift(hf, dy=-1)
            hb = shift(hb, dy=-1)
        else:
            body = b["body"]
            head = b["head"]
        return compose_layers(shadow_grid(), hb, body, head, hf, *extras_f)

    if view == "side":
        body = b["body_side_w1"] if frame % 2 else b["body_side"]
        head = b["head_side"]
        if frame % 2:
            head = shift(head, dy=1)
            hs = shift(hs, dy=1)
        return compose_layers(shadow_grid(), hs, body, head, *extras_s)

    if view == "back":
        return compose_layers(shadow_grid(), b["body_back"], hr, *extras_b)

    if view in ("sit_front", "sit"):
        return compose_layers(shadow_grid(), hb, b["body_sit"], b["head"], hf, *extras_f)

    if view == "sit_back":
        return compose_layers(shadow_grid(), b["body_sit_back"], hr, *extras_b)

    return compose_layers(shadow_grid(), hb, b["body"], b["head"], hf, *extras_f)


