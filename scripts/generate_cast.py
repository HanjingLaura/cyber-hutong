def find_photo(person):
    pid = person["photo"]
    for folder in (REF_DIR, UPLOADS):
        if not folder.exists():
            continue
        for ext in (".jpg", ".jpeg", ".png", ".webp"):
            p = folder / f"{pid}{ext}"
            if p.exists():
                return p
        for p in sorted(folder.glob(f"{pid}_*.*")):
            return p
        for p in sorted(folder.glob(f"{pid}.*")):
            return p
    return None


