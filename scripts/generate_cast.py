def _stamp(grid, x0, y0, block):
    g = [list(r) for r in grid]
    for y, row in enumerate(block):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            yy, xx = y0 + y, x0 + x
            if 0 <= yy < SH and 0 <= xx < SW:
                g[yy][xx] = ch
    return ["".join(r) for r in g]


