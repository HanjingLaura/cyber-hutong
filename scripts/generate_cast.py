def isolated_pixels(grid: list[str]) -> list[tuple[int, int]]:
    """Hair/body pixels with no 4-neighbor of the same class — scatter check."""
    solid = set()
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch not in ". U":
                solid.add((x, y))
    bad = []
    for x, y in solid:
        if not any((x + dx, y + dy) in solid for dx, dy in ((-1, 0), (1, 0), (0, -1), (0, 1))):
            bad.append((x, y))
    return bad


def neck_connected(grid: list[str]) -> bool:
    """True if some solid pixel in the jaw band touches a solid pixel below."""
    for y in range(14, 18):
        for x in range(8, 24):
            if grid[y][x] not in ". U":
                if y + 1 < SH and grid[y + 1][x] not in ". U":
                    return True
    return False


def face_holes(grid: list[str]) -> list[tuple[int, int]]:
    """Transparent pixels inside the face window that should be skin."""
    holes = []
    for y in range(5, 14):
        for x in range(9, 23):
            if grid[y][x] == ".":
                neigh = [(x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)]
                if sum(1 for nx, ny in neigh if 0 <= nx < SW and grid[ny][nx] not in ". U") >= 3:
                    holes.append((x, y))
    return holes


def qa_report(spec) -> list[str]:
    notes = []
    for view in ("front", "back", "side", "sit_front", "sit_back", "walk"):
        g = _layers_for(spec, view, 0)
        iso = isolated_pixels(g)
        if iso:
            notes.append(f"{spec['id']} {view}: isolated {iso}")
        if view in ("front", "back", "sit_front", "sit_back") and not neck_connected(g):
            notes.append(f"{spec['id']} {view}: neck not connected")
        if view == "front":
            holes = face_holes(g)
            if holes:
                notes.append(f"{spec['id']} front: face holes {holes}")
    return notes


