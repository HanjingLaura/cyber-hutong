def blank_grid():
    return ["." * SW for _ in range(SH)]


def G(text: str, name="grid") -> list[str]:
    """Parse an explicit map. Lines may be shorter than 32; they are right-padded."""
    out = []
    for i, raw in enumerate(text.strip("\n").splitlines()):
        line = raw.split("#", 1)[0].rstrip("\n")
        if len(line) > SW:
            line = line[:SW]
        out.append(line + "." * (SW - len(line)))
    while len(out) < SH:
        out.append("." * SW)
    return out[:SH]


def at(x: int, content: str) -> str:
    line = "." * x + content + "." * (SW - x - len(content))
    if len(line) != SW:
        raise ValueError(f"at({x},{content!r}) -> {len(line)}")
    return line


def assemble(rows) -> list[str]:
    """Build a 32×40 grid from (x, content) rows. None = empty."""
    out = []
    for item in rows:
        if item is None:
            out.append("." * SW)
        else:
            out.append(at(*item))
    while len(out) < SH:
        out.append("." * SW)
    return out[:SH]


def hair_only(grid: list[str]) -> list[str]:
    """Hair layers may only paint hair + outline. Skin letters would wipe the face."""
    keep = set("K1234.")
    return ["".join(ch if ch in keep else "." for ch in row) for row in grid]


def overlay(dst: list[str], src: list[str]) -> list[str]:
    out = [list(r) for r in dst]
    for y, row in enumerate(src):
        for x, ch in enumerate(row):
            if ch not in (".", " ", ""):
                out[y][x] = ch
    return ["".join(r) for r in out]


def shift(grid: list[str], dy=0, dx=0) -> list[str]:
    src = [list(r) for r in grid]
    out = [["."] * SW for _ in range(SH)]
    for y in range(SH):
        for x in range(SW):
            yy, xx = y + dy, x + dx
            if 0 <= yy < SH and 0 <= xx < SW:
                out[yy][xx] = src[y][x]
    return ["".join(r) for r in out]


def put(buf, x, y, c):
    if 0 <= x < SW and 0 <= y < SH:
        buf[y][x] = c


def paint_map(buf, grid, pal):
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch in (".", " ", ""):
                continue
            col = pal.get(ch)
            if col is not None:
                put(buf, x, y, col)


def to_image(buf) -> Image.Image:
    img = new(SW, SH)
    px = img.load()
    for y in range(SH):
        for x in range(SW):
            c = buf[y][x]
            if c is not None:
                px[x, y] = c
    return img


def shadow_grid() -> list[str]:
    g = blank_grid()
    g[29] = at(11, "UUUUUUUU")
    g[30] = at(9, "UUUUUUUUUUUU")
    g[31] = at(10, "UUUUUUUUUU")
    return g


