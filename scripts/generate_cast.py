def _bob(grid, n=1):
    if n <= 0:
        return grid
    empty = "." * SW
    return [empty] * n + grid[:-n]


def draw_cast(spec, view="front", frame=0):
    pal = spec_pal(spec)
    buf = blank()
    shadow(buf)
    cid = spec["id"]
    key = SIDE_KEY[cid]

    if view in ("front", "walk"):
        grid = FRONT[cid]
        if view == "walk":
            grid = replace_legs(grid, "walk0" if frame % 2 == 0 else "walk1")
        elif frame % 4 == 1:
            grid = _bob(grid, 1)
        paint_map(buf, grid, pal)
        return to_image(buf)

    if view == "side":
        grid = SIDE_HEAD[key]
        if frame % 2:
            grid = _bob(grid, 1)
        paint_map(buf, grid, pal)
        # neck so the authored head stamp meets the torso
        sk = pal["S"]
        ny = 11 + (frame % 2)
        for y in range(ny, ny + 5):
            for dx in (-1, 0, 1):
                put(buf, 16 + dx, y, sk)
        paint_body_frontish(buf, spec, y0=14 + (frame % 2), walk=1 if frame % 2 else 0, side=True)
        paint_arms_side(buf, spec, y0=15, frame=frame)
        return to_image(buf)

    if view == "back":
        paint_map(buf, BACK_HEAD[key], pal)
        paint_body_frontish(buf, spec, y0=18)
        return to_image(buf)

    if view in ("sit_front", "sit"):
        clipped = []
        for i, r in enumerate(FRONT[cid]):
            if i >= 22:
                clipped.append("." * SW)
            else:
                clipped.append("".join("." if ch in "PpNU" else ch for ch in r))
        paint_map(buf, clipped, pal, oy=8)
        paint_body_frontish(buf, spec, y0=29, sit=True)
        return to_image(buf)

    if view == "sit_back":
        paint_map(buf, BACK_HEAD[key], pal, oy=8)
        paint_body_frontish(buf, spec, y0=27, sit=True)
        return to_image(buf)

    paint_map(buf, FRONT[cid], pal)
    return to_image(buf)


